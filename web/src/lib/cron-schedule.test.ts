describe("cron-schedule 与 robfig/cron 对齐（黄金向量）", () => {
  it.each(GOLDEN)(
    "%s @ %s from %s",
    (expr, tz, at, expected) => {
      const result = nextCronRuns(
        expr,
        tz,
        3,
        new Date(at).getTime(),
      );
      if (expected === "ERROR") {
        expect(result.ok, `expr ${expr} should fail`).toBe(false);
        return;
      }
      if (!result.ok) {
        throw new Error(`expr ${expr} should parse, got ${JSON.stringify(result.error)}`);
      }
      // golden 中的 null 表示该次 Next 返回零值（5 年无匹配）→ 序列到此为止。
      const want = expected.filter((x): x is string => x !== null);
      const got = result.runs.map((ms) => new Date(ms).toISOString().replace(".000Z", "Z"));
      expect(got).toEqual(want);
    },
  );
});

describe("parseCronExpression 错误结构", () => {
  const err = (expr: string) => {
    const r = parseCronExpression(expr);
    expect(r.ok).toBe(false);
    return r.ok ? null : r.error;
  };

  it("空表达式", () => {
    expect(err("")!.kind).toBe("empty");
    expect(err("   ")!.kind).toBe("empty");
  });

  it("字段数不是 5", () => {
    expect(err("* * * *")!.kind).toBe("field-count");
    expect(err("0 0 * * * *")!.kind).toBe("field-count");
  });

  it("@ 描述符与 TZ 前缀被拒绝", () => {
    expect(err("@daily")!.kind).toBe("descriptor");
    expect(err("TZ=UTC 0 9 * * *")!.kind).toBe("tz-prefix");
    expect(err("CRON_TZ=Asia/Shanghai 0 9 * * *")!.kind).toBe("tz-prefix");
  });

  it("越界报出字段与范围", () => {
    const e1 = err("61 * * * *")!;
    expect(e1).toMatchObject({ kind: "above-max", field: "minute", max: 59 });
    expect(err("* 24 * * *")!.field).toBe("hour");
    expect(err("0 0 * * 7")!.field).toBe("dow");
  });

  it("反向区间 / 零步进 / 负数 / 无法解析", () => {
    expect(err("5-2 * * * *")!.kind).toBe("reversed");
    expect(err("*/0 * * * *")!.kind).toBe("zero-step");
    // "-1" 按 robfig 语义拆成 ["","1"]，空段报 syntax；step 里的负数才报 negative
    expect(err("-1 * * * *")!.kind).toBe("syntax");
    expect(err("*/-2 * * * *")!.kind).toBe("negative");
    expect(err("0 9 L * *")!.kind).toBe("syntax");
  });
});

